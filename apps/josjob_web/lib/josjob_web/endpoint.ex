defmodule JosjobWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :josjob_web

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_josjob_web_key",
    signing_salt: "iSnoGQpl",
    same_site: "Lax"
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # Socket real-time terautentikasi JWT (klien Flutter). Auth via query param
  # `token` saat handshake -> lihat JosjobWeb.UserSocket.
  socket "/socket", JosjobWeb.UserSocket,
    websocket: true,
    longpoll: false

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :josjob_web,
    gzip: not code_reloading?,
    only: JosjobWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :josjob_web
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library(),
    # Cache raw body untuk verifikasi signature webhook Stripe (hanya path webhook).
    body_reader: {JosjobWeb.Plugs.CacheBodyReader, :read_body, []}

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options

  # CORS so the Flutter web client (served from a different origin) can call the
  # JSON API at /api/*, including the browser's preflight OPTIONS. Lock origins
  # down for prod via config, e.g.:
  #   config :josjob_web, cors_origins: ["https://app.example.com"]
  # The "*" default is safe here: /api authenticates via Bearer tokens (no
  # cookies), and the browser (HTML/session) routes are served same-origin.
  # credentials: false — /api is Bearer-only, and "*" + allow-credentials is an
  # invalid CORS combination. Use an explicit origin allowlist if cookies are
  # ever added.
  plug CORSPlug,
    origin: Application.compile_env(:josjob_web, :cors_origins, "*"),
    credentials: false

  plug JosjobWeb.Router
end
